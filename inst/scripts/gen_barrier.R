#!/usr/bin/env Rscript
# Generate src/rmbl_barrier.cpp from init.c's CallEntries and rename every
# registered entry point's definition to <name>_impl. Idempotent; run from
# the package root after any change to init.c:
#   Rscript inst/scripts/gen_barrier.R
init <- readLines("src/init.c", warn = FALSE)
m <- regmatches(init, gregexpr('\\{"C_rmbl_[A-Za-z0-9_]+",\\s*\\(DL_FUNC\\) &C_rmbl_[A-Za-z0-9_]+,\\s*[0-9]+\\}', init))
m <- unlist(m)
names_ <- sub('^\\{"(C_rmbl_[A-Za-z0-9_]+)".*$', "\\1", m)
arity <- as.integer(sub("^.*,\\s*([0-9]+)\\}$", "\\1", m))
stopifnot(length(names_) >= 110, !anyDuplicated(names_))

renamed <- 0L
for (f in setdiff(list.files("src", pattern = "[.]cpp$", full.names = TRUE), "src/rmbl_barrier.cpp")) {
  s <- readLines(f, warn = FALSE)
  s2 <- s
  for (n in names_) {
    s2 <- sub(sprintf('^(extern "C" )?SEXP %s\\(', n), sprintf("\\1SEXP %s_impl(", n), s2, perl = TRUE)
  }
  if (!identical(s, s2)) {
    writeLines(s2, f)
    renamed <- renamed + 1L
  }
}
defined <- character(0)
for (f in setdiff(list.files("src", pattern = "[.]cpp$", full.names = TRUE), "src/rmbl_barrier.cpp")) {
  s <- readLines(f, warn = FALSE)
  d <- regmatches(s, regexpr('^(extern "C" )?SEXP C_rmbl_[A-Za-z0-9_]+_impl\\(', s, perl = TRUE))
  defined <- c(defined, sub("_impl\\($", "", sub('^(extern "C" )?SEXP ', "", d, perl = TRUE)))
}
# entry points written in plain C (src/*.c besides init.c: the file lock, the checked writer, the
# checked gzip reader) throw no C++ exception and report errors through R's API themselves, so they
# are registered directly and need no barrier; every other entry point must have its _impl
plain_c <- character(0)
for (f in setdiff(list.files("src", pattern = "[.]c$", full.names = TRUE), "src/init.c")) {
  s <- readLines(f, warn = FALSE)
  d <- regmatches(s, regexpr("^SEXP C_rmbl_[A-Za-z0-9_]+\\(", s, perl = TRUE))
  plain_c <- c(plain_c, sub("\\($", "", sub("^SEXP ", "", d)))
}
arity <- arity[!names_ %in% plain_c]
names_ <- setdiff(names_, plain_c)
missing <- setdiff(names_, defined)
if (length(missing)) stop("no _impl definition and no plain C definition for: ", paste(missing, collapse = ", "))
message(sprintf("%d entry points behind the barrier, %d in plain C (%s)", length(names_), length(plain_c),
                paste(plain_c, collapse = ", ")))

args_of <- function(a) paste(rep("SEXP", a), collapse = ", ")
params_of <- function(a) if (a == 0) "" else paste(sprintf("SEXP a%d", seq_len(a) - 1L), collapse = ", ")
call_of <- function(a) if (a == 0) "" else paste(sprintf("a%d", seq_len(a) - 1L), collapse = ", ")
out <- c(
  "/* GENERATED by inst/scripts/gen_barrier.R from init.c -- do not edit.",
  " *",
  " * Every registered .Call entry point is a thin wrapper: the implementation",
  " * (<name>_impl, in its own file) runs inside a try block, and any C++",
  " * exception -- std::bad_alloc, a length_error from sizing a vector with an",
  " * NA, anything a kernel throws -- becomes an R error AFTER the block has",
  " * closed, when no C++ object is alive for the longjmp to skip. Without",
  " * this an exception that reaches the extern \"C\" boundary is",
  " * std::terminate(): the R session dies, inside tryCatch() or not. A pending",
  " * interrupt caught the same way is re-raised as R's own interrupt condition.",
  " */",
  "#include <exception>",
  "#include <new>",
  "#include <string>",
  "#include <cstdio>",
  "#include <cstring>",
  "#include \"rmbl_entry.h\"",
  "",
  "extern \"C\" { int rmbl_kernel_interrupted = 0; }",
  "",
  "/* A setTimeLimit() limit (or another error R raised from its event check) taken by the poll below:",
  " * raised as R said it, an ordinary error a tryCatch() catches. Raised as an interrupt it halted",
  " * Rscript, no handler able to see it (re-test of the b617a3f CRAN stress fixes, finding 1). */",
  "static char rmbl_pending_error[512] = \"\";",
  "",
  "/* Raise R's interrupt condition from the API: signal it (so a",
  " * tryCatch(interrupt = ) handler sees it) and unwind to top level, as",
  " * R's own handler does. The pending flag was consumed by the test above,",
  " * so R_CheckUserInterrupt() would not fire again. */",
  "static void rmbl_raise_interrupt(void) {",
  "    if (rmbl_pending_error[0]) {",
  "        char m[sizeof rmbl_pending_error];",
  "        memcpy(m, rmbl_pending_error, sizeof m);",
  "        rmbl_pending_error[0] = 0;",
  "        Rf_errorcall(R_NilValue, \"%s\", m);",
  "    }",
  "    R_ParseEvalString(",
  "        \"{ signalCondition(structure(list(message = \\\"interrupt\\\", call = NULL), \"",
  "        \"    class = c(\\\"interrupt\\\", \\\"condition\\\"))); invokeRestart(\\\"abort\\\") }\",",
  "        R_BaseEnv);",
  "}",
  "",
  "/* How many barriers are active on the C stack: 0 means a LinkingTo kernel",
  " * was called by another package's .Call, with no barrier of ours to raise",
  " * the interrupt afterwards. */",
  "static int rmbl_barrier_depth = 0;",
  "",
  "static SEXP rmbl_chk_body_(void *) { R_CheckUserInterrupt(); return R_NilValue; }",
  "/* an error (the time limit) is kept, to be raised as one; an interrupt is not an error, so it",
  " * passes this handler and ends R_ToplevelExec as before */",
  "static SEXP rmbl_chk_error_(SEXP cond, void *) {",
  "    SEXP call = PROTECT(Rf_lang2(Rf_install(\"conditionMessage\"), cond));",
  "    SEXP m = PROTECT(Rf_eval(call, R_BaseEnv));",
  "    const char *t = (TYPEOF(m) == STRSXP && XLENGTH(m) > 0) ? CHAR(STRING_ELT(m, 0)) : \"\";",
  "    snprintf(rmbl_pending_error, sizeof rmbl_pending_error, \"%s\", t[0] ? t : \"error\");",
  "    UNPROTECT(2);",
  "    return R_NilValue;",
  "}",
  "static void rmbl_chk_(void *) { R_tryCatchError(rmbl_chk_body_, nullptr, rmbl_chk_error_, nullptr); }",
  "/* rmbl_fetch.cpp: turns the busy spinner when R has set a label (a no-op otherwise); every kernel's",
  " * poll for a Ctrl-C comes through here, so every polling kernel animates it */",
  "extern \"C\" void rmbl_wait_tick(void);",
  "extern \"C\" int rmbl_interrupt_pending(void) {",
  "    rmbl_wait_tick();",
  "    /* R_CheckUserInterrupt() longjmps when one is pending; run it under",
  "     * R_ToplevelExec so the jump is caught here. With a barrier active the",
  "     * kernel stops, sets the flag and the barrier raises after its",
  "     * destructors ran. With none active (a direct LinkingTo call) the",
  "     * kernel returns its sentinel and then calls",
  "     * rmbl_interrupt_raise_unbarriered() with no buffer alive. */",
  "    if (R_ToplevelExec(rmbl_chk_, nullptr) && !rmbl_pending_error[0]) return 0;",
  "    return 1;",
  "}",
  "/* For an exported kernel called with no barrier on the stack (another",
  " * package's .Call): raise R's interrupt NOW, from a frame that holds no",
  " * C++ object. The kernel calls this after its own buffers are gone -- 0.5.8",
  " * raised from inside rmbl_interrupt_pending(), over live std::vectors",
  " * (the 0.5.8 diff review). With a barrier active it does nothing: the",
  " * barrier raises after the entry point returned. */",
  "extern \"C\" void rmbl_interrupt_raise_unbarriered(void) {",
  "    if (rmbl_barrier_depth == 0) rmbl_raise_interrupt();",
  "}",
  "",
  "/* is a barrier body on the stack: an argument error there is thrown (rmbl_arg_error) */",
  "extern \"C\" int rmbl_barrier_active(void) {",
  "    return rmbl_barrier_depth > 0;",
  "}",
  "",
  "static void rmbl_set_msg(char *to, const char *m) {",
  "    std::snprintf(to, 1024, \"%s\", m);",
  "}",
  "",
  "template <class F>",
  "struct rmbl_call {",
  "    F *f;",
  "    SEXP r;",
  "    char msg[1024];   /* not a std::string: Rf_errorcall() below jumps over its destructor */",
  "    int kind;",
  "};",
  "",
  "/* The body, under R_UnwindProtect: every C++ exception is caught here, so",
  " * none crosses R's C frames. */",
  "template <class F>",
  "static SEXP rmbl_body(void *data) {",
  "    rmbl_call<F> *c = static_cast<rmbl_call<F> *>(data);",
  "    try {",
  "        c->r = (*c->f)();",
  "        if (rmbl_kernel_interrupted) c->kind = 1;",
  "    } catch (const rmbl::Interrupt &) {",
  "        c->kind = 1;",
  "    } catch (const rmbl::Fail &e) {",
  "        rmbl_set_msg(c->msg, e.what());   /* an argument error: said as Rf_error() said it, without the entry's name */",
  "        c->kind = 3;",
  "    } catch (const std::bad_alloc &) {",
  "        rmbl_set_msg(c->msg, \"out of memory\");",
  "        c->kind = 2;",
  "    } catch (const std::exception &e) {",
  "        rmbl_set_msg(c->msg, e.what());",
  "        c->kind = 2;",
  "    } catch (...) {",
  "        rmbl_set_msg(c->msg, \"unexpected C++ exception\");",
  "        c->kind = 2;",
  "    }",
  "    return R_NilValue;",
  "}",
  "",
  "/* An R error raised inside the body (an argument check's Rf_error) jumps",
  " * past the guard: the depth and the flag are put back on the way out. Left",
  " * raised, the depth stayed above 0 for the session and every later",
  " * unbarriered interrupt was dropped (network stress test of 5e1dce5). */",
  "static void rmbl_unwound(void *, Rboolean jump) {",
  "    if (jump) {",
  "        --rmbl_barrier_depth;",
  "        rmbl_kernel_interrupted = 0;",
  "    }",
  "}",
  "",
  "template <class F>",
  "static SEXP rmbl_guard(const char *name, F f) {",
  "    rmbl_call<F> c;",
  "    c.f = &f;",
  "    c.r = R_NilValue;",
  "    c.kind = 0;",
  "    SEXP cont = PROTECT(R_MakeUnwindCont());",
  "    ++rmbl_barrier_depth;",
  "    rmbl_kernel_interrupted = 0;   /* nothing from an earlier call may leak in */",
  "    R_UnwindProtect(rmbl_body<F>, &c, rmbl_unwound, nullptr, cont);",
  "    UNPROTECT(1);",
  "    const int kind = c.kind;",
    "    SEXP r = c.r;",
  "    /* every path leaves the flag clear and the depth balanced BEFORE the",
  "     * longjmp an error or interrupt makes below */",
  "    rmbl_kernel_interrupted = 0;",
  "    --rmbl_barrier_depth;",
  "    if (kind == 0) return r;",
  "    if (kind == 1) {",
  "        rmbl_raise_interrupt();",
  "        Rf_errorcall(R_NilValue, \"%s: interrupted\", name);",
  "    }",
  "    if (kind == 3) Rf_errorcall(R_NilValue, \"%s\", c.msg);",
  "    Rf_errorcall(R_NilValue, \"%s: %s\", name, c.msg);",
  "    return R_NilValue;",
  "}",
  "",
  "extern \"C\" {",
  sprintf("SEXP %s_impl(%s);", names_, vapply(arity, args_of, "")),
  "}",
  "",
  "extern \"C\" {",
  unlist(Map(function(n, a) c(
    sprintf("SEXP %s(%s) {", n, params_of(a)),
    sprintf("    return rmbl_guard(\"%s\", [&] { return %s_impl(%s); });", n, n, call_of(a)),
    "}"), names_, arity)),
  "}"
)
writeLines(out, "src/rmbl_barrier.cpp")
cat(sprintf("barrier: %d entries, renamed definitions in %d file(s)\n", length(names_), renamed))
