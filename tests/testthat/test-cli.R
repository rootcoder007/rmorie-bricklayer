# The command line: verbs, usage errors, the bare-question rule, the launcher.

cli_run <- function(...) {
  e <- new.env()
  e$out <- character()
  st <- blcli(c(...), out = function(x) e$out <- c(e$out, x))
  list(status = st, text = paste(e$out, collapse = ""))
}

test_that("version, help and a verb's usage exit 0", {
  r <- cli_run("version")
  expect_identical(r$status, 0L)
  expect_match(r$text, "^rmoriebricklayer [0-9]")
  r <- cli_run("help")
  expect_identical(r$status, 0L)
  expect_match(r$text, "usage: ", fixed = TRUE)
  expect_match(r$text, "Capsules", fixed = TRUE)
  r <- cli_run("help", "start")
  expect_match(r$text, "Getting started", fixed = TRUE)
  expect_match(r$text, "5. The curated tables", fixed = TRUE)
  r <- cli_run("help", "llm")
  expect_match(r$text, "Where ask sends a prompt", fixed = TRUE)
  expect_match(r$text, "One call only", fixed = TRUE)
  r <- cli_run("help", "r")
  expect_match(r$text, "library(rmoriebricklayer)", fixed = TRUE)
  r <- cli_run("logout", "--help")
  expect_identical(r$status, 0L)
  expect_match(r$text, "usage: .* logout")
})

test_that("unknown verbs, options and topics are usage errors", {
  r <- cli_run("nonsense")
  expect_identical(r$status, 2L)
  expect_match(r$text, "unknown verb 'nonsense'", fixed = TRUE)
  r <- cli_run("doctr")
  expect_match(r$text, "did you mean", fixed = TRUE)
  r <- cli_run("logout", "--nosuch")
  expect_identical(r$status, 2L)
  expect_match(r$text, "unknown option --nosuch", fixed = TRUE)
  r <- cli_run("help", "nosuchtopic")
  expect_identical(r$status, 2L)
  r <- cli_run("version", "extra")
  expect_identical(r$status, 2L)
  expect_match(r$text, "version takes no arguments", fixed = TRUE)
  r <- cli_run("functions", "--", "x")
  expect_identical(r$status, 2L)
  expect_match(r$text, "takes no arguments after --", fixed = TRUE)
  expect_error(blcli("version", out = "x"), "must be a function")
  expect_error(blcli(c("version", NA)), "no NA")
})

test_that("the words split into verb, options and a tail", {
  w <- .bl_cli_words(c("aye", "--fresh", "--", "--q"))
  expect_identical(w$verb, "ask")
  expect_identical(w$rest, "--fresh")
  expect_identical(w$tail_args, "--q")
  expect_identical(.bl_cli_words(character())$verb, "help")
  expect_identical(.bl_cli_flag(c("--out", "f.csv"), "--out"), "f.csv")
  expect_null(.bl_cli_flag("x", "--out"))
  expect_error(.bl_cli_flag("--out", "--out"), "needs a value")
  expect_true("--port" %in% .bl_cli_known_opts(character())$app)
  expect_identical(.bl_cli_known_opts("reset")$config, "--force")
  expect_null(.bl_cli_known_opts("show")$config)
})

test_that("ask takes its options once and refuses a retired route", {
  o <- .bl_v_ask_opts(c("--model", "m", "--fresh", "hello"))
  expect_identical(o$mdl, "m")
  expect_true(o$fresh)
  expect_identical(o$rest, "hello")
  expect_null(o$rte)
  expect_error(.bl_v_ask_opts(c("--model", "a", "--model", "b")), "once")
  expect_error(.bl_v_ask_opts(c("--route", "nowhere", "q")), "--route takes")
})

test_that("a plain question is asked, a command or a key is not", {
  expect_true(.bl_bare_question("how do I weight a survey?"))
  expect_false(.bl_bare_question("cnfig set openai.key"))
  expect_false(.bl_bare_question("my urls.txt"))
  expect_false(.bl_bare_question(character()))
  expect_false(.bl_bare_question("what is sk-abcdefgh1234567890xyz?"))
  expect_true(.bl_key_shaped("sk-abcdefgh1234567890"))
  expect_true(.bl_key_shaped("abcd1234efgh ijkl5678mnop qrst9012uvwx"))
  expect_true(.bl_key_prefixed("ghp_abcdefghij12"))
  expect_false(.bl_key_prefixed("sk-abcdefghijkl"))
  expect_false(.bl_key_grouped("survey design replicates"))
  expect_false(.bl_key_shaped("survey_design_replicates"))
  expect_true(.bl_verb_near("dcotor"))
  expect_false(.bl_verb_near("is"))
})

test_that("every verb has a usage line", {
  v <- .bl_verb_usage(NULL)
  expect_true(all(c("login", "ask", "verify", "sign", "version") %in% v))
  expect_match(.bl_verb_usage("data", "rmbl"), "^usage: rmbl data")
  expect_null(.bl_verb_usage("nonsense"))
})

test_that("a shell read gives the line, or an interrupt", {
  ok <- structure("\002RMBL-LINE\002 typed ", status = 0L)
  expect_identical(.bl_readline_sh_line(ok), "typed")
  expect_match(.bl_readline_script(TRUE), "stty -echo", fixed = TRUE)
  expect_false(grepl("stty", .bl_readline_script(FALSE), fixed = TRUE))
  old <- Sys.getenv("RMBL_PROMPT", unset = NA)
  Sys.setenv(RMBL_PROMPT = "x")
  .bl_restore_prompt(NA)
  expect_identical(Sys.getenv("RMBL_PROMPT", unset = "unset"), "unset")
  .bl_restore_prompt("y")
  expect_identical(Sys.getenv("RMBL_PROMPT"), "y")
  .bl_restore_prompt(old)
})

test_that("instcli writes the launchers and refuses bad names", {
  skip_on_os("windows")
  d <- withr::local_tempdir()
  expect_message(instcli(dir = d), "Installed")
  expect_true(file.exists(file.path(d, "rmoriebricklayer")))
  expect_true(file.exists(file.path(d, "rmbl")))
  sh <- readLines(file.path(d, "rmbl"))
  expect_identical(sh[[1L]], "#!/bin/sh")
  expect_true(any(grepl("export RMBL_PROG=rmbl", sh, fixed = TRUE)))
  expect_error(instcli(dir = d, name = ""), "command names")
  expect_error(instcli(dir = d, name = "a/b"), "command names")
  expect_error(instcli(dir = d, name = character()), "command names")
})
