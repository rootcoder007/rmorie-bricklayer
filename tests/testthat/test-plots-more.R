# The many-plot helpers: each draws to a null device and returns the data it
# drew.

test_that("the distribution plots draw and return their data", {
  grDevices::pdf(NULL)
  on.exit(grDevices::dev.off(), add = TRUE)
  set.seed(21)
  x <- c(stats::rnorm(100), stats::rnorm(100, 2))
  g <- rep(c("a", "b"), each = 100)
  r <- plotrdg(x, g)
  expect_identical(unique(r$grp), c("a", "b"))
  expect_equal(sum(r$y[r$grp == "a"]) * diff(r$x[1:2]), 1, tolerance = 0.02)
  expect_s3_class(plotrdg(c(x, 5), c(g, "lone"), main = "Ridges"), "data.frame")
  e <- plotecdf(x, g)
  expect_identical(e$y[e$grp == "a"][100L], 1)
  expect_s3_class(plotecdf(x), "data.frame")
  v <- plotvln(c(x, 9), c(g, "c"))
  expect_identical(attr(v, "summary")$median[1L], stats::median(x[1:100]))
  h <- plothex(x, x + stats::rnorm(200), bins = 10)
  expect_identical(sum(h$count), 200L)
  expect_identical(sum(plothex(c(1, 1, 1), c(2, 2, 2))$count), 3L)
  w <- stats::rexp(200)
  k <- plotgain(w, g)
  expect_identical(attr(k, "gini")[["a"]], as.numeric(ginicoef(w[1:100])))
  expect_identical(tail(k$value[k$grp == "a"], 1), 1)
  expect_error(plotrdg("a"), "`x` must be a numeric vector")
  expect_error(plotrdg(1:3, 1:2), "one entry per value")
  expect_error(plotecdf(c(1, NA)), "at least two finite")
  expect_error(plothex(1:3, "a"), "plothex: `y` must be numeric")
  expect_error(plothex(c(1, NA, 3), c(NA, 2, 4)), "at least two points")
  expect_error(plotgain(c(-1, 2, 3)), "must not be negative")
})

test_that("the series plots draw and return their data", {
  grDevices::pdf(NULL)
  on.exit(grDevices::dev.off(), add = TRUE)
  days <- seq(as.Date("2023-12-25"), as.Date("2024-03-01"), by = "day")
  cal <- plotcal(days, c(NA, seq_along(days)[-1L]))
  expect_identical(nrow(cal), length(days))
  expect_true(all(cal$wday %in% 1:7))
  expect_s3_class(plotcal(as.character(days[1:3]), c(1, 1, 1)), "data.frame")
  expect_error(plotcal("not a date", 1), "plotcal: `x` must be dates")
  d <- expand.grid(year = 2015:2020, area = c("n", "s", "e"))
  d$v <- c(1:6, 6:1, c(3, 3, 3, 3, 3, 3))
  hz <- plothrz(d$v, d$year, d$area, bands = 2)
  expect_true(all(hz$band %in% 0:2))
  expect_s3_class(plothrz(rep(1, 3), 1:3), "data.frame")
  sm <- plotsm(d$v, d$year, d$area, main = "Small")
  expect_identical(nrow(sm), 18L)
  expect_s3_class(plotsm(1:4, c("q1", "q2", "q3", "q4")), "data.frame")
  b <- plotbump(d$v, d$year, d$area)
  expect_identical(b$rank[b$grp == "n" & b$prd == 2015], 3)
  expect_identical(b$rank[b$grp == "s" & b$prd == 2015], 1)
  asc <- plotbump(d$v, d$year, d$area, desc = FALSE)
  expect_identical(asc$rank[asc$grp == "n" & asc$prd == 2015], 1)
  expect_error(plotsm("a", 1, 1), "`y` must be a numeric vector")
  expect_error(plotsm(1:3, 1:2), "one entry per value")
  expect_error(plotsm(1:2, c(NA, NA)), "no value has both")
})
